"""SIx Neural Core -- the interface identity of the SIx secure mesh.

The SIx interface is NOT a human head and NOT a chatbot avatar: it is a
floating holographic object with an adaptive core -- the **SIx Neural
Core**. A non-human form gives the mesh its own identity without making
it look like a virtual person. The core is a glass sphere with a glowing
hexagonal heart, suspended over a holographic pedestal; what it is
*doing* is shown by how it moves and what colour it burns.

Five visual states (the design spec, verbatim):

    IDLE       -- Slowly floating and breathing
    LISTENING  -- Cyan glowing rings
    THINKING   -- Rapid neural pulses
    RESPONDING -- Expanding communication waves
    LEARNING   -- New particles connecting

This module is the deterministic model of that interface: a state
machine (:class:`NeuralCore`) with a legal-transition map, the per-state
visual parameter table (:func:`params_for`), and a PIL renderer
(:func:`render_frame`) that draws any state at any animation phase.
Rendering is a pure function of ``(state, phase, size, seed)`` -- no
wall clock, no unseeded randomness -- so the shipped assets in
``assets/neural-core/`` can be regenerated byte-for-byte by
``scripts/generate_neural_core_assets.py``.

Stdlib + Pillow only. This module deliberately does NOT import torch:
the interface model must stay usable on a bare edge box that only
renders the mesh's face.
"""
import logging
import math
import random
from dataclasses import dataclass
from enum import Enum

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

try:
    from PIL import Image, ImageDraw, ImageFilter, ImageFont
except ImportError as exc:  # pragma: no cover - Pillow is present in the dev/CI image
    raise ImportError(
        "neural_core_interface needs Pillow for rendering: pip install pillow"
    ) from exc

INTERFACE_NAME = "SIx Neural Core"
DEFAULT_SEED = 0x516  # fixed layout seed -- the same scene for every frame
DEFAULT_SIZE = 900

_FONT_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
_FONT_REGULAR = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


class CoreState(str, Enum):
    """The five visual states of the SIx Neural Core."""

    IDLE = "IDLE"
    LISTENING = "LISTENING"
    THINKING = "THINKING"
    RESPONDING = "RESPONDING"
    LEARNING = "LEARNING"


STATE_ORDER = (
    CoreState.IDLE,
    CoreState.LISTENING,
    CoreState.THINKING,
    CoreState.RESPONDING,
    CoreState.LEARNING,
)

# Legal transitions. The working cycle is
# IDLE -> LISTENING -> THINKING -> RESPONDING -> IDLE / LEARNING, and
# ANY state may return to IDLE. Self-transitions are illegal.
TRANSITIONS = {
    CoreState.IDLE: frozenset({CoreState.LISTENING}),
    CoreState.LISTENING: frozenset({CoreState.THINKING, CoreState.IDLE}),
    CoreState.THINKING: frozenset({CoreState.RESPONDING, CoreState.IDLE}),
    CoreState.RESPONDING: frozenset({CoreState.LEARNING, CoreState.IDLE}),
    CoreState.LEARNING: frozenset({CoreState.LISTENING, CoreState.IDLE}),
}


class IllegalTransitionError(ValueError):
    """Raised when a Neural Core state transition is not in the legal map."""


@dataclass(frozen=True)
class StateVisualParams:
    """Visual parameters for one Neural Core state (sizes at a 900 px canvas).

    ``pulse_rate`` is in cycles per animation loop; THINKING is the fast
    state by design (rapid neural pulses), IDLE the slow one (breathing).
    """

    state: CoreState
    appearance: str           # the design-spec line, verbatim
    dominant_color: tuple     # RGB the core burns in this state
    pulse_rate: float         # pulses per animation loop
    ring_count: int           # concentric aura rings (LISTENING)
    wave_rate: float          # expanding-wave speed, 0 = no waves (RESPONDING)
    link_rate: float          # particle-connection growth, 0..1 (LEARNING)
    float_amplitude: float    # vertical float amplitude, px @ 900
    breathing_amplitude: float  # radial breathing scale, fraction of R


