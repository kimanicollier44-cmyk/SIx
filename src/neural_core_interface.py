def params_for(state) -> StateVisualParams:
    """The visual parameter row for ``state`` (accepts CoreState or str)."""
    return _STATE_PARAMS[CoreState(state)]


def legal_transitions(state) -> frozenset:
    """The set of states reachable in one step from ``state``."""
    return TRANSITIONS[CoreState(state)]


class NeuralCore:
    """The SIx Neural Core state machine.

    Starts IDLE. ``transition()`` follows the legal map only; anything
    else raises :class:`IllegalTransitionError`. History is a logical
    tick counter (1, 2, 3, ...) -- never a wall-clock timestamp -- so
    runs are reproducible.
    """

    def __init__(self, initial=CoreState.IDLE):
        self._state = CoreState(initial)
        self._tick = 0
        self._history = [(0, None, self._state)]

    @property
    def state(self) -> CoreState:
        return self._state

    @property
    def params(self) -> StateVisualParams:
        return params_for(self._state)

    @property
    def history(self) -> tuple:
        """(tick, from_state, to_state) rows; tick 0 is the initial state."""
        return tuple(self._history)

    def can_transition(self, target) -> bool:
        return CoreState(target) in TRANSITIONS[self._state]

    def transition(self, target) -> CoreState:
        target = CoreState(target)
        if target not in TRANSITIONS[self._state]:
            legal = ", ".join(sorted(s.value for s in TRANSITIONS[self._state]))
            raise IllegalTransitionError(
                f"illegal Neural Core transition {self._state.value} -> {target.value}; "
                f"legal from {self._state.value}: {legal}"
            )
        self._tick += 1
        self._history.append((self._tick, self._state, target))
        self._state = target
        logger.info("Neural Core: %s (tick %d)", target.value, self._tick)
        return self._state

    def reset(self) -> CoreState:
        """Force back to IDLE from any state (the universal safe state)."""
        if self._state is not CoreState.IDLE:
            self._tick += 1
            self._history.append((self._tick, self._state, CoreState.IDLE))
            self._state = CoreState.IDLE
        return self._state


# --------------------------------------------------------------------------
# Deterministic layout: one seeded scene shared by every state and phase,
# so the orb, its circuit nodes and its particle field never jump around
# between frames -- only the state's effects change.
# --------------------------------------------------------------------------

def _scene(seed: int):
    rng = random.Random(seed)
    stars = [(rng.random(), rng.random(), rng.uniform(0.15, 0.8), rng.uniform(0.6, 1.8))
             for _ in range(120)]
    traces = []
    for _ in range(14):
        x, y = rng.random(), rng.random()
        pts = [(x, y)]
        for _ in range(rng.randint(2, 4)):
            if rng.random() < 0.5:
                x = min(1.0, max(0.0, x + rng.uniform(-0.16, 0.16)))
            else:
                y = min(1.0, max(0.0, y + rng.uniform(-0.16, 0.16)))
            pts.append((x, y))
        traces.append(pts)
    # circuit nodes inside the sphere: (angle, radius fraction)
    nodes = [(rng.uniform(0.0, 2.0 * math.pi), rng.uniform(0.15, 0.85),
              rng.uniform(0.5, 1.0)) for _ in range(26)]
    # particles orbiting outside the sphere: (angle, radius x R, size)
    particles = [(rng.uniform(0.0, 2.0 * math.pi), rng.uniform(1.18, 1.55),
                  rng.uniform(0.6, 1.4)) for _ in range(18)]
    # candidate LEARNING links: particle index pairs, nearest-first
    pairs = []
    for i in range(len(particles)):
        for j in range(i + 1, len(particles)):
            ax, ay = _polar(particles[i][0], particles[i][1])
            bx, by = _polar(particles[j][0], particles[j][1])
            pairs.append((math.hypot(ax - bx, ay - by), i, j))
    pairs.sort()
    links = [(i, j) for _, i, j in pairs[:28]]
    wave_bars = [rng.uniform(0.25, 1.0) for _ in range(25)]
    return stars, traces, nodes, particles, links, wave_bars


def _polar(angle: float, radius: float):
    return radius * math.cos(angle), radius * math.sin(angle)


def _font(path: str, px: int):
    try:
        return ImageFont.truetype(path, px)
    except (OSError, IOError):
        return ImageFont.load_default()


def _draw_label(draw: ImageDraw.ImageDraw, text: str, cx: float, y: float,
                px: int, color: tuple):
    """Letter-spaced state label, centred on cx."""
    spaced = " ".join(list(text))
    font = _font(_FONT_BOLD, px)
    bbox = draw.textbbox((0, 0), spaced, font=font)
    w = bbox[2] - bbox[0]
    draw.text((cx - w / 2.0, y), spaced, font=font, fill=color + (255,))


def render_frame(state, phase: float = 0.0, size: int = DEFAULT_SIZE,
                 seed: int = DEFAULT_SEED) -> Image.Image:
    """Draw one frame of the SIx Neural Core.

    ``phase`` is the position inside the state's animation loop, in
    [0, 1). The result is a pure function of (state, phase, size, seed):
    same arguments, byte-identical image.
    """
    params = params_for(state)
    state = params.state
    phase = float(phase) % 1.0
    ss = 2  # supersampling factor for smooth glow edges
    W = size * ss
    color = params.dominant_color
    stars, traces, nodes, particles, links, wave_bars = _scene(seed)

    # --- background: deep-navy vertical gradient, stars, circuit traces ---
    top, bottom = (5, 12, 30), (1, 2, 9)
    bg = Image.new("RGB", (W, W))
    grad = Image.new("RGB", (1, W))
    for yy in range(W):
        t = yy / max(1, W - 1)
        grad.putpixel((0, yy), tuple(int(top[c] + (bottom[c] - top[c]) * t)
                                     for c in range(3)))
    bg = grad.resize((W, W))
    bgd = ImageDraw.Draw(bg, "RGBA")
    for sx, sy, alpha, r in stars:
        bgd.ellipse([sx * W - r * ss, sy * W - r * ss,
                     sx * W + r * ss, sy * W + r * ss],
                    fill=(140, 190, 255, int(70 * alpha)))
    for pts in traces:
        bgd.line([(x * W, y * W) for x, y in pts],
                 fill=(16, 52, 96, 90), width=max(1, ss))
        for x, y in pts:
            bgd.ellipse([x * W - 2 * ss, y * W - 2 * ss,
                         x * W + 2 * ss, y * W + 2 * ss],
                        fill=(30, 90, 150, 110))

    # --- geometry for this phase ---
    cx = W * 0.5
    scale = W / 900.0
    float_px = params.float_amplitude * scale * math.sin(2.0 * math.pi * phase)
    cy = W * 0.47 + float_px
    breathe = 1.0 + params.breathing_amplitude * math.sin(2.0 * math.pi * phase)
    R = W * 0.265 * breathe

    fx = Image.new("RGBA", (W, W), (0, 0, 0, 0))   # effects behind the orb
    fxd = ImageDraw.Draw(fx, "RGBA")

    # RESPONDING: expanding communication waves
    if params.wave_rate > 0.0:
        for i in range(3):
            frac = (phase * params.wave_rate + i / 3.0) % 1.0
            rr = R * (1.05 + 1.6 * frac)
            alpha = int(190 * (1.0 - frac))
            fxd.ellipse([cx - rr, cy - rr, cx + rr, cy + rr],
                        outline=color + (alpha,), width=max(1, int(3 * ss * (1.0 - frac)) + 1))

    # LISTENING: cyan aura rings + an audio waveform strip
    if params.ring_count > 0:
        for i in range(params.ring_count):
            wobble = math.sin(2.0 * math.pi * phase + i * 1.1) * W * 0.006
            rr = R * (1.14 + 0.17 * i) + wobble
            alpha = 200 - 45 * i
            fxd.ellipse([cx - rr, cy - rr, cx + rr, cy + rr],
                        outline=color + (alpha,), width=3 * ss)
        bar_w = W * 0.011
        gap = W * 0.006
        total_w = len(wave_bars) * (bar_w + gap)
        x0 = cx - total_w / 2.0
        y_base = W * 0.185
        for i, h in enumerate(wave_bars):
            amp = h * (0.45 + 0.55 * abs(math.sin(math.pi * phase + i * 0.55)))
            bh = W * 0.055 * amp
            x = x0 + i * (bar_w + gap)
            fxd.rounded_rectangle([x, y_base - bh, x + bar_w, y_base + bh],
                                  radius=bar_w / 2.0, fill=color + (170,))

    # THINKING: rapid radial neural pulses
    if state is CoreState.THINKING:
        pulse = 2.0 * math.pi * phase * params.pulse_rate
        for k in range(36):
            ang = k * (2.0 * math.pi / 36.0)
            wave = 0.5 + 0.5 * math.sin(pulse + ang * 3.0)
            r0 = R * 1.0
            r1 = R * (1.10 + 0.30 * wave)
            fxd.line([cx + r0 * math.cos(ang), cy + r0 * math.sin(ang),
                      cx + r1 * math.cos(ang), cy + r1 * math.sin(ang)],
                     fill=color + (int(90 + 130 * wave),), width=2 * ss)

    # --- the orb itself ---
    orb = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    od = ImageDraw.Draw(orb, "RGBA")

    # orbital ellipse ring (the holographic "orbit" around the sphere)
    od.ellipse([cx - R * 1.28, cy - R * 0.34, cx + R * 1.28, cy + R * 0.34],
               outline=color + (110 if params.ring_count else 60,), width=2 * ss)

    # sphere body: layered translucent fills, brighter toward the core
    for frac, alpha in ((1.0, 26), (0.8, 30), (0.58, 38), (0.36, 52)):
        rr = R * frac
        od.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=color + (alpha,))
    # glass shell outlines
    od.ellipse([cx - R, cy - R, cx + R, cy + R], outline=color + (215,), width=3 * ss)
    od.ellipse([cx - R * 0.93, cy - R * 0.93, cx + R * 0.93, cy + R * 0.93],
               outline=(200, 235, 255, 70), width=1 * ss)
    # top-left glass highlight arc
    od.arc([cx - R * 0.86, cy - R * 0.86, cx + R * 0.86, cy + R * 0.86],
           start=140, end=235, fill=(235, 248, 255, 150), width=3 * ss)

    # circuit nodes inside the sphere, wired to the core
    node_pts = []
    for ang, rf, bright in nodes:
        nx, ny = cx + R * rf * math.cos(ang), cy + R * rf * math.sin(ang)
        node_pts.append((nx, ny))
        od.line([cx, cy, nx, ny], fill=color + (36,), width=1 * ss)
    for (nx, ny), (_, _, bright) in zip(node_pts, nodes):
        rr = 2.6 * ss * bright + 1.2 * ss
        od.ellipse([nx - rr, ny - rr, nx + rr, ny + rr],
                   fill=color + (int(120 + 110 * bright),))

    # particles around the sphere (+ LEARNING connections between them)
    ppts = [(cx + R * rf * math.cos(ang), cy + R * rf * math.sin(ang), sz)
            for ang, rf, sz in particles]
    if state is CoreState.LEARNING:
        visible = 3 + int(phase * max(1, len(links) - 3))
        connected = set()
        for i, j in links[:visible]:
            od.line([ppts[i][0], ppts[i][1], ppts[j][0], ppts[j][1]],
                    fill=color + (165,), width=2 * ss)
            connected.add(i)
            connected.add(j)
        for idx, (px_, py_, sz) in enumerate(ppts):
            rr = (3.4 if idx in connected else 2.0) * ss * sz
            alpha = 235 if idx in connected else 90
            od.ellipse([px_ - rr, py_ - rr, px_ + rr, py_ + rr],
                       fill=color + (alpha,))
    else:
        for px_, py_, sz in ppts:
            rr = 2.2 * ss * sz
            od.ellipse([px_ - rr, py_ - rr, px_ + rr, py_ + rr],
                       fill=color + (120,))

    # hexagonal core -- the adaptive heart of the orb
    hex_scale = 1.0
    if state is CoreState.THINKING:
        hex_scale = 1.0 + 0.07 * math.sin(2.0 * math.pi * phase * params.pulse_rate)
    hr = R * 0.42 * hex_scale
    hex_pts = [(cx + hr * math.cos(math.radians(60 * k - 90)),
                cy + hr * math.sin(math.radians(60 * k - 90))) for k in range(6)]
    od.polygon(hex_pts, fill=color + (46,))
    od.line(hex_pts + [hex_pts[0]], fill=color + (255,), width=4 * ss, joint="curve")
    hr2 = hr * 0.55
    hex2 = [(cx + hr2 * math.cos(math.radians(60 * k - 90)),
             cy + hr2 * math.sin(math.radians(60 * k - 90))) for k in range(6)]
    od.line(hex2 + [hex2[0]], fill=(235, 250, 255, 190), width=2 * ss, joint="curve")
    core_r = R * 0.075
    od.ellipse([cx - core_r, cy - core_r, cx + core_r, cy + core_r],
               fill=(255, 255, 255, 255))
    od.ellipse([cx - core_r * 1.9, cy - core_r * 1.9, cx + core_r * 1.9, cy + core_r * 1.9],
               outline=color + (160,), width=2 * ss)

    # --- pedestal: the holographic projector base under the floating core ---
    ped = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    pd = ImageDraw.Draw(ped, "RGBA")
    py = W * 0.865
    prx, pry = W * 0.30, W * 0.042
    pd.ellipse([cx - prx, py - pry, cx + prx, py + pry], fill=color + (30,))
    pd.ellipse([cx - prx, py - pry, cx + prx, py + pry], outline=color + (150,), width=2 * ss)
    pd.ellipse([cx - prx * 0.62, py - pry * 0.62, cx + prx * 0.62, py + pry * 0.62],
               outline=color + (90,), width=1 * ss)

    # --- composite: background, effects, glow, orb, pedestal ---
    img = bg.convert("RGBA")
    img.alpha_composite(fx)
    glow = orb.filter(ImageFilter.GaussianBlur(radius=W * 0.012))
    img.alpha_composite(glow)
    img.alpha_composite(orb)
    img.alpha_composite(ped)

    d = ImageDraw.Draw(img, "RGBA")
    _draw_label(d, state.value, cx, W * 0.062, int(W * 0.036), color)
    sub_font = _font(_FONT_REGULAR, int(W * 0.016))
    sub = INTERFACE_NAME.upper()
    bbox = d.textbbox((0, 0), sub, font=sub_font)
    d.text((cx - (bbox[2] - bbox[0]) / 2.0, W * 0.935), sub,
           font=sub_font, fill=(150, 180, 220, 200))

    img = img.convert("RGB")
    if ss > 1:
        img = img.resize((size, size), Image.LANCZOS)
    return img


def state_table() -> tuple:
    """All five states in cycle order, with their visual parameters."""
    return tuple(params_for(state) for state in STATE_ORDER)


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="SIx Neural Core interface model")
    parser.add_argument("--render", metavar="STATE",
                        help="render one frame of STATE to --out (PNG)")
    parser.add_argument("--out", default="neural-core-frame.png")
    parser.add_argument("--phase", type=float, default=0.3)
    parser.add_argument("--size", type=int, default=DEFAULT_SIZE)
    args = parser.parse_args()

    if args.render:
        frame = render_frame(args.render, phase=args.phase, size=args.size)
        frame.save(args.out)
        print(f"rendered {args.render} -> {args.out} ({args.size}x{args.size})")
    else:
        print(f"{INTERFACE_NAME} -- five visual states")
        for row in state_table():
            legal = ", ".join(sorted(s.value for s in legal_transitions(row.state)))
            print(f"  {row.state.value:<10} {row.appearance:<34} "
                  f"color={row.dominant_color} pulse={row.pulse_rate}/loop -> {legal}")
